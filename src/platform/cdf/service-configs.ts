export function resolveCdfServiceConfig(
  serviceKey: string
): CdfServiceConfig | undefined {
  const raw = serviceKey.trim();
  if (!raw) return undefined;
  if (CDF_SERVICE_CONFIGS[raw]) return CDF_SERVICE_CONFIGS[raw];
  const byId = CDF_CONFIG_BY_ID[raw];
  if (byId) return byId;
  const alias = ALIASES[raw.toLowerCase()];
  if (alias) return CDF_CONFIG_BY_ID[alias];
  return undefined;
}

export function listCdfServiceIds(): string[] {
  return Object.keys(CDF_CONFIG_BY_ID);
}
