import type { CdfFlowPhase, CdfServiceConfig } from "./types";

function phase(
  partial: Omit<CdfFlowPhase, "generator"> & { generator?: CdfFlowPhase["generator"] },
): CdfFlowPhase {
  const generator =
    partial.generator ??
    (partial.type === "routes"
      ? // Config route cards are a user choice gate — do not auto-fan-out.
        // Services that need AI-generated routes set generator: "launch_routes" explicitly.
        partial.routes?.length
          ? "none"
          : "launch_routes"
      : partial.type === "text-approval"
        ? "text"
        : partial.type === "final"
          ? "materialize"
          : partial.type === "output" ||
              partial.type === "mockup" ||
              partial.type === "multi-output"
            ? "image"
            : "none");
  return { ...partial, generator };
}

